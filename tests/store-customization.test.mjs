import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const js=ts.transpileModule(fs.readFileSync('lib/store-customization.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
const {bagsFirst,visibleBrands,themeVariables}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const categories=[['all'],['makeup'],['bags'],['evening','','','','bags']];
assert.deepEqual(bagsFirst(categories).map(c=>c[0]),['all','bags','makeup','evening']);
assert.equal(categories[1][0],'makeup');
const settings={categories,brands:['A','B','C','D'],brandMeta:{A:{categoryIds:['bags']},B:{categoryIds:['makeup'],home:false},C:{hidden:true},D:{categoryIds:['evening']}}};
assert.deepEqual(visibleBrands(settings,'bags'),['A','D']);
assert.deepEqual(visibleBrands(settings,'evening'),['A','D']);
assert.deepEqual(visibleBrands(settings,undefined,true),['A','D']);
assert.deepEqual(visibleBrands(settings,'makeup'),['B']);
assert.deepEqual(themeVariables(settings),{});
const themed={...settings,theme:{light:{card:'#ffffff',text:'url(evil)',ticker:'#123456'},dark:{card:'#000000'}}};
assert.equal(themeVariables(themed)['--custom-card'],'#ffffff');
assert.equal(themeVariables(themed)['--custom-text'],undefined);
assert.equal(themeVariables(themed,true)['--custom-card'],'#000000');
console.log('Customization tests passed: navigation, category brands, homepage visibility and safe isolated palettes.');
const {orderCollection}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const products=[{id:'a',sortOrder:1},{id:'b',sortOrder:2},{id:'c',sortOrder:3}];
const ranked={...settings,collectionOrder:{best:['c','a'],featured:['b','a']}};
assert.deepEqual(orderCollection(products,ranked,'best').map(p=>p.id),['c','a','b']);
assert.deepEqual(orderCollection(products,ranked,'featured').map(p=>p.id),['b','a','c']);
assert.deepEqual(products.map(p=>p.id),['a','b','c']);
const socialJs=ts.transpileModule(fs.readFileSync('lib/social-links.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
const {safeSocialUrl}=await import('data:text/javascript;base64,'+Buffer.from(socialJs).toString('base64'));
assert.equal(safeSocialUrl('javascript:alert(1)'),undefined);
assert.equal(safeSocialUrl('https://user:password@example.com'),undefined);
assert.equal(safeSocialUrl('https://instagram.com/najd'),'https://instagram.com/najd');
assert.equal(safeSocialUrl(''),undefined);
console.log('PASS independent collection order and safe footer URLs.');
