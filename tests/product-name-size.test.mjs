import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import ts from 'typescript';
const exports = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/product-name-size.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports});
const {normalizeBaseSize,readBaseSize,productNameWithSize} = exports;
assert.equal(normalizeBaseSize('٢٠'),'20');
assert.equal(normalizeBaseSize('٢٥٫٥'),'25.5');
for(const v of ['-2','0','abc','1001']) assert.throws(()=>normalizeBaseSize(v));
const names={ar:'شنطة حجم القاعدة 20سم',en:'Bag — Base size 20 cm',he:'תיק — גודל בסיס 20 ס״מ'};
assert.equal(readBaseSize(names),'20');
const next=productNameWithSize(names,'25');
assert.equal(next.ar,'شنطة بحجم قاعدة 25 سم');
assert.equal(productNameWithSize(next,'25').ar,next.ar);
const cleared=productNameWithSize(next,'');
assert.equal(cleared.ar,'شنطة'); assert.equal(cleared.en,'Bag'); assert.equal(cleared.he,'תיק');
assert.equal(productNameWithSize({ar:'شنطة طول قاعدة',en:'Bag',he:'תיק'},'').ar,'شنطة');
assert.equal(productNameWithSize({ar:'شنطة',en:'',he:''},20).en,'');
console.log('PASS optional size, removal, replacement, Arabic digits, decimals, and all three languages');
